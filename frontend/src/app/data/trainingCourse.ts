/**
 * Содержание раздела «Обучение» для партнёров.
 *
 * Курс — шесть коротких видео по 40–50 секунд. К каждому уроку: конспект
 * (текст озвучки, переписанный в тезисы) и шаги, которые партнёр делает
 * в кабинете после просмотра.
 *
 * Видео лежат в `frontend/public/training/` и раздаются самим сайтом,
 * поэтому внешние видеосервисы не нужны.
 */

export type LessonIcon = 'intro' | 'client' | 'documents' | 'tasks' | 'finance' | 'chat';

export interface LessonStep {
  text: string;
  to?: string;
  linkLabel?: string;
}

export interface TrainingLesson {
  /** Стабильный ключ урока. По нему сохраняется прогресс просмотра. */
  key: string;
  number: number;
  title: string;
  /** Одна строка: о чём урок. */
  subtitle: string;
  /** Длительность ролика в секундах. */
  duration: number;
  videoUrl: string;
  /** Обложка карточки: тёмный постер с названием урока. */
  cover: string;
  icon: LessonIcon;
  accent: {
    /** Фон кружка с иконкой. */
    soft: string;
    /** Цвет иконки и акцентов. */
    text: string;
    /** Градиент обложки. */
    gradient: string;
    /** Базовый цвет акцента для инлайн-стилей. */
    hex: string;
  };
  conspect: string[];
  steps: LessonStep[];
  /** Куда идти в кабинете, чтобы применить урок. */
  section: { label: string; to: string };
}

