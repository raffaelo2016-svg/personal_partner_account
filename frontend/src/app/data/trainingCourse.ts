export function findLesson(key: string): TrainingLesson | undefined {
  return TRAINING_LESSONS.find((lesson) => lesson.key === key);
}

export function formatLessonDuration(seconds: number): string {
  const safe = Math.max(0, Math.round(seconds));
  const minutes = Math.floor(safe / 60);
  const rest = safe % 60;
  return `${minutes}:${rest.toString().padStart(2, '0')}`;
}

export const TRAINING_TOTAL_DURATION = TRAINING_LESSONS.reduce(
  (sum, lesson) => sum + lesson.duration,
  0,
);
