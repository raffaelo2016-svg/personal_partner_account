REGION_TIMEZONES: dict[str, str] = {
    region: timezone for timezone, regions in REGIONS_BY_TIMEZONE.items() for region in regions
}

REGION_NAMES = frozenset(REGION_TIMEZONES)


def normalize_region(value: str | None) -> str | None:
    """Trim and validate a Russian region name."""
    if value is None:
        return None
    normalized = value.strip()
    if normalized not in REGION_NAMES:
        raise ValueError("Неизвестный регион")
    return normalized


def timezone_for_region(region: str | None) -> str | None:
    if not region:
        return None
    return REGION_TIMEZONES.get(region)
